import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const apiJsonPath = path.resolve(__dirname, "../src/api/api.json");
const schemaPath = path.resolve(__dirname, "../src/api/schema.d.ts");
const modelsPath = path.resolve(__dirname, "../src/types/models.ts");
const templateVarsPath = path.resolve(
    __dirname,
    "../src/components/node-config/nodes/templateVariables.ts",
);

if (!fs.existsSync(apiJsonPath)) {
    console.error("api.json not found. Run openapi generation first.");
    process.exit(1);
}

if (!fs.existsSync(schemaPath)) {
    console.error("schema.d.ts not found. Run openapi-typescript first.");
    process.exit(1);
}

const apiJson = JSON.parse(fs.readFileSync(apiJsonPath, "utf8"));
const schemasJson = apiJson.components?.schemas || {};

let schemaContent = fs.readFileSync(schemaPath, "utf8");

// Locate components.schemas inside schema.d.ts
const compStart = schemaContent.indexOf("export interface components {");
if (compStart === -1) {
    console.error("export interface components not found in schema.d.ts");
    process.exit(1);
}

const schemasStart = schemaContent.indexOf("schemas: {", compStart);
if (schemasStart === -1) {
    console.error("schemas: { not found inside components in schema.d.ts");
    process.exit(1);
}

let level = 0;
let schemasEnd = -1;
for (let i = schemasStart + "schemas: {".length - 1; i < schemaContent.length; i++) {
    if (schemaContent[i] === "{") level++;
    if (schemaContent[i] === "}") {
        level--;
        if (level === 0) {
            schemasEnd = i + 1;
            break;
        }
    }
}

if (schemasEnd === -1) {
    console.error("Could not find matching closing brace for schemas in schema.d.ts");
    process.exit(1);
}

const schemasBody = schemaContent.substring(schemasStart + "schemas: {".length, schemasEnd - 1);

// Parse schemas from schema.d.ts
const parsedSchemas = [];
let i = 0;

while (i < schemasBody.length) {
    while (i < schemasBody.length && /\s/.test(schemasBody[i])) i++;
    if (i >= schemasBody.length) break;

    let docComment = "";
    if (schemasBody.substring(i, i + 3) === "/**") {
        const commentEnd = schemasBody.indexOf("*/", i);
        if (commentEnd !== -1) {
            docComment = schemasBody.substring(i, commentEnd + 2);
            i = commentEnd + 2;
            while (i < schemasBody.length && /\s/.test(schemasBody[i])) i++;
        }
    }

    const keyMatch = schemasBody.substring(i).match(/^([A-Za-z0-9_$]+)\s*:\s*/);
    if (!keyMatch) break;

    const schemaName = keyMatch[1];
    i += keyMatch[0].length;

    let valStart = i;
    let braceDepth = 0;
    let valEnd = -1;

    for (; i < schemasBody.length; i++) {
        const char = schemasBody[i];
        if (char === "{" || char === "(" || char === "<") braceDepth++;
        else if (char === "}" || char === ")" || char === ">") braceDepth--;
        else if (char === ";" && braceDepth === 0) {
            valEnd = i;
            i++;
            break;
        }
    }

    if (valEnd === -1) break;

    const typeDef = schemasBody.substring(valStart, valEnd).trim();
    parsedSchemas.push({ name: schemaName, docComment, typeDef });
}

// ── 1. Generate models.ts ──────────────────────────────────────────────────

let modelsContent = `// AUTO-GENERATED FILE. DO NOT EDIT.\n`;
modelsContent += `// This file is automatically generated by scripts/generate-models.js\n\n`;

for (const s of parsedSchemas) {
    if (s.docComment) {
        modelsContent += `${s.docComment}\n`;
    }
    // Replace components["schemas"]["ModelName"] with ModelName
    const cleanedTypeDef = s.typeDef.replace(/components\["schemas"\]\["([^"]+)"\]/g, "$1");

    if (cleanedTypeDef.startsWith("{")) {
        modelsContent += `export interface ${s.name} ${cleanedTypeDef}\n\n`;
    } else {
        modelsContent += `export type ${s.name} = ${cleanedTypeDef};\n\n`;
    }
}

fs.mkdirSync(path.dirname(modelsPath), { recursive: true });
fs.writeFileSync(modelsPath, modelsContent);

console.log(
    `[SUCCESS] Generated models.ts with ${parsedSchemas.length} model interfaces/types.`,
);

// ── 2. Update schema.d.ts ──────────────────────────────────────────────────

const importStatement = `import type * as Models from "../types/models";\n`;
if (!schemaContent.startsWith(importStatement)) {
    schemaContent = importStatement + schemaContent;
}

// Re-calculate schemasStart and schemasEnd because schemaContent might have shifted due to import
const newCompStart = schemaContent.indexOf("export interface components {");
const newSchemasStart = schemaContent.indexOf("schemas: {", newCompStart);

let newLevel = 0;
let newSchemasEnd = -1;
for (let j = newSchemasStart + "schemas: {".length - 1; j < schemaContent.length; j++) {
    if (schemaContent[j] === "{") newLevel++;
    if (schemaContent[j] === "}") {
        newLevel--;
        if (newLevel === 0) {
            newSchemasEnd = j + 1;
            break;
        }
    }
}

let newSchemasBlock = `schemas: {\n`;
for (const s of parsedSchemas) {
    if (s.docComment) {
        newSchemasBlock += `        ${s.docComment}\n`;
    }
    newSchemasBlock += `        ${s.name}: Models.${s.name};\n`;
}
newSchemasBlock += `    }`;

schemaContent =
    schemaContent.substring(0, newSchemasStart) +
    newSchemasBlock +
    schemaContent.substring(newSchemasEnd);

fs.writeFileSync(schemaPath, schemaContent);

console.log(
    `[SUCCESS] Updated schema.d.ts components.schemas to reference Models interfaces.`,
);

// ── 3. Generate templateVariables.ts ────────────────────────────────────────

const SCHEMA_TO_VAR = [
    { schema: "ServerData", prefix: "server", group: "server" },
    { schema: "ClientData", prefix: "server.client", group: "client" },
    { schema: "StatPointData", prefix: "metric", group: "metric" },
];

function snakeToTitle(str) {
    return str
        .replace(/_/g, " ")
        .replace(/\b\w/g, (c) => c.toUpperCase());
}

const labels = [];

for (const { schema, prefix, group } of SCHEMA_TO_VAR) {
    const schemaObj = schemasJson[schema];
    if (!schemaObj?.properties) {
        console.warn(
            `[WARN] Schema "${schema}" not found or has no properties — skipping template variables for group "${group}".`,
        );
        continue;
    }

    for (const propName of Object.keys(schemaObj.properties)) {
        labels.push({
            key: `${prefix}.${propName}`,
            label: snakeToTitle(propName),
            group,
            description: `${snakeToTitle(propName)} (${schema})`,
        });
    }
}

const lines = [];
lines.push(`import type { ServerData, ClientData, StatPointData } from '@/types/models';`);
lines.push(``);
lines.push(`type ServerVarKey = \`server.\${keyof ServerData & string}\`;`);
lines.push(`type ClientVarKey = \`server.client.\${keyof ClientData & string}\`;`);
lines.push(`type MetricVarKey = \`metric.\${keyof StatPointData & string}\`;`);
lines.push(``);
lines.push(`type TemplateVariableKey = ServerVarKey | ClientVarKey | MetricVarKey;`);
lines.push(``);
lines.push(`export interface TemplateVariable {`);
lines.push(`    key: TemplateVariableKey;`);
lines.push(`    label: string;`);
lines.push(`    group: 'server' | 'client' | 'metric';`);
lines.push(`    description: string;`);
lines.push(`}`);
lines.push(``);
lines.push(`const LABELS: Record<TemplateVariableKey, { label: string; group: TemplateVariable['group']; description: string }> = {`);

for (const { key, label, group, description } of labels) {
    const pad = Math.max(0, 32 - key.length - 2);
    lines.push(
        `    '${key}'${" ".repeat(pad)}: { label: '${label}', group: '${group}', description: '${description}' },`,
    );
}

lines.push(`};`);
lines.push(``);
lines.push(`export const TEMPLATE_VARIABLES: TemplateVariable[] = (Object.entries(LABELS) as [TemplateVariableKey, typeof LABELS[TemplateVariableKey]][]).map(`);
lines.push(`    ([key, meta]) => ({ key, ...meta }),`);
lines.push(`);`);
lines.push(``);
lines.push(`export function filterVariables(query: string): TemplateVariable[] {`);
lines.push(`    const q = query.toLowerCase();`);
lines.push(`    return TEMPLATE_VARIABLES.filter(`);
lines.push(`        (v) => v.key.toLowerCase().includes(q) || v.label.toLowerCase().includes(q),`);
lines.push(`    );`);
lines.push(`}`);
lines.push(``);

fs.mkdirSync(path.dirname(templateVarsPath), { recursive: true });
fs.writeFileSync(templateVarsPath, lines.join("\n"));

console.log(
    `[SUCCESS] Generated templateVariables.ts with ${labels.length} template variables.`,
);
